"""Tests for the ``netlist`` subcommand (pure parsing, no kicad-cli needed).

The primary fixture is the script-generated example board
``examples/diffpair_showcase`` (see README "Example boards"; generated by
``tests/make_boards.py``); its netlist statistics are known by construction
and verified against the KiCad-bundled pcbnew API
(tests/test_netlist_crosscheck.py), so the tests assert exact counts
(14 footprints, 27 pads, 20 declared nets including the unnamed net 0,
19 named nets, 1 pad without a net).

"Bare vs full project": the netlist lives entirely inside the ``.kicad_pcb``
file, so parsing a lone board copy (no ``.kicad_pro`` anywhere near it)
must produce the same content as parsing the board inside the full example
project directory -- unlike DRC results, which are context-sensitive (see
README "Board context sensitivity").

These tests are written pytest-style (plain ``test_*`` functions with bare
asserts) and also run under the bundled stdlib runner ``tests/run_tests.py``.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from pcb_periph.canonical import dumps_canonical  # noqa: E402
from pcb_periph.netlist import (  # noqa: E402
    DEFAULT_RULE_SET,
    run_netlist,
    scan_diffpairs,
)

CLEAN_PCB = os.path.join(
    REPO_ROOT, "examples", "diffpair_showcase", "diffpair_showcase.kicad_pcb"
)

# pinned statistics of the example board (by construction in
# tests/make_boards.py; verified against the KiCad-bundled pcbnew API in
# tests/test_netlist_crosscheck.py)
FIXTURE_STATS = {
    "footprints": 14,
    "pads": 27,
    "pads_no_net": 1,
    "pads_with_net": 26,
    "nets_declared": 20,
    "nets_named": 19,
    "diffpair_pairs": 5,
    "diffpair_unpaired": 5,
    "diffpair_suspicious": 2,
}


def _run_cli(args, env_overrides=None):
    env = {k: v for k, v in os.environ.items() if k != "KICAD_CLI"}
    env.update(env_overrides or {})
    return subprocess.run(
        [sys.executable, "-m", "pcb_periph", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=REPO_ROOT,
        env=env,
        timeout=120,
    )


def _payload(proc):
    return json.loads(proc.stdout)


def _board(payload):
    assert payload["boards"], "payload has no board items"
    return payload["boards"][0]


def test_netlist_help_documents_exit_codes():
    proc = _run_cli(["netlist", "--help"])
    assert proc.returncode == 0, proc.stderr
    for code, meaning in (
        ("0", "all boards parsed"),
        ("2", "configuration error"),
        ("3", "input file unreadable"),
    ):
        assert code in proc.stdout and meaning in proc.stdout


def test_netlist_clean_board_fields_and_counts():
    proc = _run_cli(["netlist", CLEAN_PCB])
    assert proc.returncode == 0, proc.stderr
    payload = _payload(proc)
    assert payload["schema_version"] == "1.0.0"
    assert payload["command"] == "netlist"
    assert payload["diffpair_rule_set"] == DEFAULT_RULE_SET
    board = _board(payload)
    assert board["status"] == "ok"
    assert board["board"].endswith("diffpair_showcase.kicad_pcb")
    assert "\\" not in board["board"]

    # source identification comes from the file header
    assert board["source"]["generator"] == "pcbnew"
    assert board["source"]["version"] == 20241229

    # layers carry index/name/type (standard KiCad two-layer stack)
    layers = board["layers"]
    assert len(layers) == 20
    by_name = {layer["name"]: layer for layer in layers}
    assert by_name["F.Cu"]["index"] == 0
    assert by_name["F.Cu"]["type"] == "signal"
    assert by_name["B.Cu"]["index"] == 31
    assert by_name["Edge.Cuts"]["index"] == 44

    # footprints carry reference/layer/position
    footprints = board["footprints"]
    assert len(footprints) == FIXTURE_STATS["footprints"]
    r2 = next(fp for fp in footprints if fp["reference"] == "R2")
    assert r2["layer"] == "F.Cu"
    assert r2["position"] == {"x": 30, "y": 35}
    assert r2["pads"] == 2
    assert r2["library_id"].startswith("Generated:")

    # pads carry ownership, net, shape and type
    pads = board["pads"]
    assert len(pads) == FIXTURE_STATS["pads"]
    pad = next(p for p in pads if p["footprint"] == "R2" and p["pad"] == "1")
    assert pad["shape"] == "rect"
    assert pad["type"] == "smd"
    assert pad["net"] == {"id": 3, "name": "DATA_P"}

    # nets: name -> pad reference list
    nets = board["nets"]
    assert len(nets) == FIXTURE_STATS["nets_named"]
    assert nets["GND"] == [
        "R6-2", "R7-2", "R8-2", "R9-2", "R10-2", "J1-2", "C1-2",
    ]
    assert nets["VCC"] == ["J1-1", "C1-1"]
    assert nets["CLK+"] == ["R1-1"]

    # one pad carries no net at all in this board (the mounting hole)
    assert board["pads_no_net"] == FIXTURE_STATS["pads_no_net"]

    # diffpair candidates with the rule set name recorded (the scan uses
    # the same engine as the diffpair subcommand, rule set kicad-doc-v1)
    diffpair = board["diffpair_candidates"]
    assert diffpair["rule_set"] == DEFAULT_RULE_SET == "kicad-doc-v1"
    assert [group["group"] for group in diffpair["suffix_groups"]] == [
        "plus_minus", "p_n", "p_n",
    ]
    assert [group["suffix_style"] for group in diffpair["suffix_groups"]] == [
        "symbol", "separator", "bare",
    ]
    # by construction: five pairs covering every suffix style (the two CLK
    # pairs share a base across groups), five unpaired halves and two
    # suspicious findings (see tests/test_diffpair.py)
    assert [
        (pair["positive"], pair["negative"]) for pair in diffpair["pairs"]
    ] == [
        ("CLK-P", "CLK-N"),
        ("CLK+", "CLK-"),
        ("DATA_P", "DATA_N"),
        ("USB.P", "USB.N"),
        ("USB_DP", "USB_DN"),
    ]
    assert [half["net"] for half in diffpair["unpaired"]] == [
        "AUX-N", "AUX_P", "LONE_P", "PIEZO_IN", "SENSE+",
    ]
    assert all(half["polarity"] for half in diffpair["unpaired"])
    assert [
        (item["kind"], item["base"]) for item in diffpair["suspicious"]
    ] == [
        ("mixed_suffix_style", "AUX"),
        ("suffixless_twin", "DATA"),
    ]

    # stats agree with the payload contents
    for key, value in FIXTURE_STATS.items():
        assert board["stats"][key] == value, key
    assert sum(len(refs) for refs in nets.values()) == FIXTURE_STATS["pads_with_net"]
    assert sum(fp["pads"] for fp in footprints) == FIXTURE_STATS["pads"]
    summary = payload["summary"]
    assert summary["boards"] == 1 and summary["boards_ok"] == 1
    assert summary["pads"] == FIXTURE_STATS["pads"]


def test_netlist_bare_board_matches_full_project_context():
    """A lone .kicad_pcb copy parses to the same netlist content."""
    work = tempfile.mkdtemp()
    try:
        bare = os.path.join(work, "diffpair_showcase.kicad_pcb")
        shutil.copyfile(CLEAN_PCB, bare)
        assert not os.path.exists(os.path.join(work, "diffpair_showcase.kicad_pro"))
        proc = _run_cli(["netlist", bare])
        assert proc.returncode == 0, proc.stderr
        bare_board = _board(_payload(proc))
    finally:
        shutil.rmtree(work, ignore_errors=True)
    assert bare_board["status"] == "ok"

    full_payload, exit_code = run_netlist([CLEAN_PCB], cwd=REPO_ROOT)
    assert exit_code == 0
    full_board = full_payload["boards"][0]
    # everything except the path anchor must be identical
    for key in (
        "source",
        "layers",
        "footprints",
        "pads",
        "nets",
        "pads_no_net",
        "diffpair_candidates",
        "stats",
    ):
        assert bare_board[key] == full_board[key], key


def test_netlist_double_run_canonical_byte_equal():
    work = tempfile.mkdtemp()
    try:
        out1 = os.path.join(work, "run1.json")
        out2 = os.path.join(work, "run2.json")
        common = ["netlist", CLEAN_PCB, "--canonical"]
        proc1 = _run_cli([*common, "--out", out1])
        proc2 = _run_cli([*common, "--out", out2])
        assert proc1.returncode == 0 and proc2.returncode == 0
        bytes1 = open(out1, "rb").read()
        bytes2 = open(out2, "rb").read()
        assert bytes1 == bytes2
        digest = hashlib.sha256(bytes1).hexdigest()
        assert digest == hashlib.sha256(bytes2).hexdigest()
        assert b"timing_ms" not in bytes1

        # a non-canonical run canonicalized in post reproduces the same bytes
        out3 = os.path.join(work, "run3.json")
        proc3 = _run_cli(["netlist", CLEAN_PCB, "--out", out3])
        assert proc3.returncode == 0, proc3.stderr
        payload3 = json.load(open(out3, encoding="utf-8"))
        assert payload3["timing_ms"] >= 0
        assert dumps_canonical(payload3).encode("utf-8") == bytes1
    finally:
        shutil.rmtree(work, ignore_errors=True)


def test_netlist_batch_two_inputs():
    work = tempfile.mkdtemp()
    try:
        copy = os.path.join(work, "other_name.kicad_pcb")
        shutil.copyfile(CLEAN_PCB, copy)
        proc = _run_cli(["netlist", CLEAN_PCB, copy])
        assert proc.returncode == 0, proc.stderr
        payload = _payload(proc)
        assert payload["summary"]["boards"] == 2
        assert payload["summary"]["boards_ok"] == 2
        assert payload["summary"]["pads"] == 2 * FIXTURE_STATS["pads"]
    finally:
        shutil.rmtree(work, ignore_errors=True)


def test_netlist_rule_set_none_and_unknown():
    proc = _run_cli(["netlist", CLEAN_PCB, "--diffpair-rules", "none"])
    assert proc.returncode == 0, proc.stderr
    board = _board(_payload(proc))
    assert board["diffpair_candidates"]["rule_set"] == "none"
    assert board["diffpair_candidates"]["suffix_groups"] == []
    assert board["diffpair_candidates"]["pairs"] == []
    assert board["diffpair_candidates"]["unpaired"] == []
    assert board["diffpair_candidates"]["suspicious"] == []
    assert board["stats"]["diffpair_unpaired"] == 0
    assert board["stats"]["diffpair_suspicious"] == 0

    # the old minimal rule set is gone; unknown names are rejected by
    # the CLI argument parser
    for name in ("bogus", "basic"):
        proc = _run_cli(["netlist", CLEAN_PCB, "--diffpair-rules", name])
        assert proc.returncode != 0, name
        assert "invalid choice" in proc.stderr


def test_netlist_never_touches_kicad_cli():
    """netlist is pure parsing: a bogus KICAD_CLI must not break it."""
    bogus = os.path.join(tempfile.mkdtemp(), "kicad-cli-does-not-exist.exe")
    proc = _run_cli(["netlist", CLEAN_PCB], env_overrides={"KICAD_CLI": bogus})
    assert proc.returncode == 0, proc.stderr
    assert _board(_payload(proc))["status"] == "ok"


def test_netlist_missing_board_exits_three():
    missing = os.path.join(REPO_ROOT, "examples", "no_such_board.kicad_pcb")
    proc = _run_cli(["netlist", missing])
    assert proc.returncode == 3, proc.stderr
    board = _board(_payload(proc))
    assert board["status"] == "unreadable"
    assert "not found" in board["error"]


def test_netlist_wrong_suffix_exits_two():
    work = tempfile.mkdtemp()
    other = os.path.join(work, "not_a_board.txt")
    with open(other, "w", encoding="utf-8") as handle:
        handle.write("(not a board)\n")
    proc = _run_cli(["netlist", other])
    assert proc.returncode == 2, proc.stderr
    board = _board(_payload(proc))
    assert board["status"] == "config_error"


def test_netlist_unparseable_file_exits_two():
    work = tempfile.mkdtemp()
    for name, text in (
        ("garbage.kicad_pcb", "just some plain text\n"),
        ("truncated.kicad_pcb", "(kicad_pcb (version 20241229)\n"),
        ("wrong_root.kicad_pcb", '(symbol_libtext "something")\n'),
    ):
        path = os.path.join(work, name)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)
        proc = _run_cli(["netlist", path])
        assert proc.returncode == 2, (name, proc.stderr)
        board = _board(_payload(proc))
        assert board["status"] == "parse_error", name
        assert board["error"]


def test_scan_diffpairs_uses_diffpair_engine():
    """The candidate scan is the diffpair subcommand's engine (pad count 1)."""
    names = ["CLK+", "CLK-", "DATA_P", "DATA_N", "LONE_P", "BUSY", "_P"]
    result = scan_diffpairs(names)
    assert result["rule_set"] == "kicad-doc-v1"
    assert [(p["positive"], p["negative"]) for p in result["pairs"]] == [
        ("CLK+", "CLK-"), ("DATA_P", "DATA_N"),
    ]
    assert [half["net"] for half in result["unpaired"]] == ["LONE_P", "_P"]
    assert result["pairs"][0]["pads"] == {"positive": 1, "negative": 1}


def test_scan_diffpairs_rejects_unknown_rule_set():
    try:
        scan_diffpairs(["A+", "A-"], rule_set="bogus")
    except ValueError as exc:
        assert "unknown diffpair rule set" in str(exc)
    else:
        raise AssertionError("expected ValueError for unknown rule set")
